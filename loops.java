public class loops{
    public static void main(String[] args){
        int s=1;
        while (s<=10){
            System.out.println("Hello!");
            s++;
        }
        
        int a=1;
        do{
            System.out.println("Hello");
            a++;
        }while(a>10);
        
        for(int i=1;i<=10;i++){
            System.out.println("Hello");
        }

    }
}